export function extractOTFFeatures(font: Font): string[] {
  const features = new Set<string>();

  const gsubFeatures = (font.tables as any).gsub?.features;
  if (Array.isArray(gsubFeatures)) {
    for (const f of gsubFeatures) {
      if (f.tag) features.add(f.tag);
    }
  }

  const gposFeatures = (font.tables as any).gpos?.features;
  if (Array.isArray(gposFeatures)) {
    for (const f of gposFeatures) {
      if (f.tag) features.add(f.tag);
    }
  }

  return Array.from(features).sort();
}
